def find_maximum_integer(integer_set):
    # Using the max function to find the maximum integer
    maximum_integer = max(integer_set)
    
    # Printing the result
    print("Maximum Integer:", maximum_integer)

# Example set of integers
example_set = {10, 5, 8, 15, 2, 20}

# Call the function with the example set
find_maximum_integer(example_set)